import { useState } from "react";
import { CalendarClock, KeyRound, LoaderCircle, Lock, Sparkles, TriangleAlert, Webhook } from "lucide-react";
import { useServerFn } from "@tanstack/react-start";
import { toast } from "sonner";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { asset } from "@/data/asset";
import { aiFormatEnv } from "@/lib/assistant/assistant.functions";
import { cn } from "@/lib/utils";
import { CopyButton, FieldRow, Panel, SecretValue } from "../primitives";
import { errorMessage } from "../use-ai";

type EnvFormat = Awaited<ReturnType<typeof aiFormatEnv>>;
type EnvField = EnvFormat["variables"][number]["field"];

const DEFAULT_FORMAT: EnvFormat = {
  comment: "Instagram - Newton Badminton · generated by AI",
  variables: [
    { field: "publicKey", name: "INSTAGRAM_PUBLIC_KEY" },
    { field: "secretToken", name: "INSTAGRAM_SECRET_TOKEN" },
    { field: "webhookUrl", name: "INSTAGRAM_WEBHOOK_URL" },
  ],
};

// The AI only names the variables; real values are filled in here, in the browser.
function valueFor(field: EnvField, masked: boolean) {
  const a = asset.api;
  if (field === "publicKey") return masked ? `${a.publicKey.slice(0, 13)}…` : a.publicKey;
  if (field === "secretToken") return masked ? "sk_live_********" : a.secretToken;
  return a.webhookUrl;
}

function buildEnv(format: EnvFormat) {
  return [
    `# ${format.comment}`,
    ...format.variables.map((v) => `${v.name}=${valueFor(v.field, false)}`),
    `# expires ${asset.api.expiration}`,
  ].join("\n");
}

export function ApiTab() {
  const a = asset.api;
  const formatEnv = useServerFn(aiFormatEnv);
  const [format, setFormat] = useState<EnvFormat>(DEFAULT_FORMAT);
  const [formatting, setFormatting] = useState(false);
  const [aiFormatted, setAiFormatted] = useState(false);

  const copyEnv = async () => {
    setFormatting(true);
    let next = format;
    try {
      next = await formatEnv();
      setFormat(next);
      setAiFormatted(true);
    } catch (err) {
      setFormatting(false);
      toast.error("AI gagal menyusun .env", { description: errorMessage(err) });
      return;
    }
    setFormatting(false);
    try {
      await navigator.clipboard.writeText(buildEnv(next));
      toast.success("Format .env disalin", {
        description: `${next.variables.length} variabel siap ditempel ke project kamu.`,
      });
    } catch {
      toast.error("Gagal menyalin ke clipboard", { description: "Tekan tombol lagi untuk menyalin." });
    }
  };

  return (
    <div className="space-y-6">
      <Panel title="API & Developer" description="Kredensial integrasi untuk SocioAPI Playground.">
        <div className="divide-y divide-border">
          <FieldRow icon={<KeyRound />} label="Public API Key">
            <span className="font-mono text-sm">{a.publicKey.slice(0, 13)}…</span>
            <CopyButton value={a.publicKey} label="Public API key" />
          </FieldRow>
          <FieldRow icon={<Lock />} label="Secret Token">
            <SecretValue value={a.secretToken} label="Secret token" prefix="sk_live_" mask="********" />
          </FieldRow>
          <FieldRow icon={<Webhook />} label="Webhook URL">
            <span className="font-mono text-sm">{a.webhookUrl}</span>
            <CopyButton value={a.webhookUrl} label="Webhook URL" />
          </FieldRow>
          <FieldRow icon={<CalendarClock />} label="Expiration Date">
            <span>{a.expiration}</span>
            <Badge variant="warning">
              <TriangleAlert className="size-3" />
              Segera kedaluwarsa
            </Badge>
          </FieldRow>
        </div>
      </Panel>

      <Panel
        title="Preview .env"
        description={
          aiFormatted
            ? "Disusun AI. Nilai rahasia diisi di perangkatmu, tidak dikirim ke AI."
            : "AI menyusun variabel dengan penamaan standar."
        }
      >
        <div className="space-y-5 p-5">
          <pre
            className={cn(
              "overflow-x-auto rounded-lg border border-border bg-muted px-5 py-4 font-mono text-[13px] leading-relaxed text-foreground transition-opacity",
              formatting && "ai-shimmer opacity-70",
            )}
          >
            <span className="text-muted-foreground"># {format.comment}</span>
            {format.variables.map((v) => (
              <span key={v.field}>
                {"\n"}
                {v.name}=<span className="text-success-foreground">{valueFor(v.field, true)}</span>
              </span>
            ))}
          </pre>
          <Button variant="ai" size="lg" className="w-full" onClick={copyEnv} disabled={formatting}>
            {formatting ? <LoaderCircle className="animate-spin" /> : <Sparkles />}
            {formatting ? "AI sedang menyusun…" : "AI Format & Copy as .env"}
          </Button>
        </div>
      </Panel>
    </div>
  );
}
